COMPILED_STEM_RULES = [(label, [re.compile(p) for p in pats]) for label, pats in STEM_RULES]


def classify_stem(stem: str):
    """발문(또는 문항에 대한 설명) 문자열을 보고 역량 태그를 매긴다.
    새 유형(형식논리·강화약화·개요·문단배열)과 기존 15개 역량이 섞여 나올 수 있다.
    """
    tags = []
    for label, pats in COMPILED_STEM_RULES:
        if any(p.search(stem) for p in pats):
            tags.append(label)
    return tags


