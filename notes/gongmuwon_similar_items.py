def find_similar_items(skill_tags, all_items, top_n=8, max_per_exam=2):
    """주어진 역량 태그 목록과 하나라도 겹치는 기출문항을 겹치는 태그 수 순으로
    정렬해 반환한다. skill_tags가 모두 NEW_SKILLS_NO_CSAT_MATCH에 속하면(즉
    기존 15개 역량과 전혀 안 겹치면) 빈 리스트를 반환한다 — 억지 매칭 금지.

    같은 회차(exam_id)의 문항들이 몰려서 결과를 독점하지 않도록, 회차당 최대
    max_per_exam개까지만 채택하며 최대한 여러 연도에 걸쳐 뽑는다(학생이 특정
    한두 회차만 반복하기보다 다양한 연도의 유사 문항을 골고루 접하도록).
    """
    if not skill_tags:
        return []
    scored = []
    for it in all_items:
        it_tags = set(it.get("역량", []))
        overlap = it_tags & set(skill_tags)
        if overlap:
            scored.append((len(overlap), it))
    scored.sort(key=lambda x: -x[0])

    picked = []
    per_exam = Counter()
    for n, it in scored:
        exam = it.get("exam_id", it.get("연도"))
        if per_exam[exam] >= max_per_exam:
            continue
        picked.append((n, it))
        per_exam[exam] += 1
        if len(picked) >= top_n:
            break
    return picked


