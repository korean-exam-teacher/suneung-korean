def area_for(qn, cfg):
    if qn <= 10:
        return "화법과 작문"
    if qn <= 12:
        return "언어와 매체"
    for s, e in cfg["독서"]:
        if s <= qn <= e:
            return "독서"
    for s, e in cfg["문학"]:
        if s <= qn <= e:
            return "문학"
    raise ValueError(f"no block for qn={qn}")


def build(exam_id):
    cfg = EXAMS[exam_id]
    raw = open(f"/tmp/old_raw/{exam_id.replace('-', '.')}.txt", encoding="utf-8").read()
    text = ab_clean(raw)
    # 1~5번(듣기평가)은 제외 — start_num=6
    items = parse_exam(text, exam_id, cfg["meta"], start_num=6, end_num=50)
    choice_map = choices_in_zone(text, 6, 50)
    for it in items:
        qn = it["문항번호"]
        it["영역"] = area_for(qn, cfg)
        it["선택지"] = choice_map.get(qn, [])
    return items


def main():
    all_items = {}
    for exam_id in EXAMS:
        items = build(exam_id)
        all_items[exam_id] = items
        n_choice_ok = sum(1 for it in items if len(it["선택지"]) == 5)
        n_bogi = sum(1 for it in items if it["보기"])
        from collections import Counter
        area_c = Counter(it["영역"] for it in items)
        print(f"{exam_id}: {len(items)}문항(6~50), 선택지 5개 확보 {n_choice_ok}, 보기 {n_bogi}, 영역분포 {dict(area_c)}")

    json.dump(all_items, open("/home/claude/items_2009_2013_raw.json", "w", encoding="utf-8"),
               ensure_ascii=False, indent=1)
    print("저장: items_2009_2013_raw.json")


if __name__ == "__main__":
    main()
